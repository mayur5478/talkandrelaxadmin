import React from "react";
import { useGetCallTranscriptQuery } from "../../services/monitoring";
import { Modal, ModalBody, ModalFooter, Button, Spinner, ErrorBanner } from "../v2/ui";

/**
 * CallTranscriptModal — redacted speech-to-text of one call, from the moderation service.
 * Phone/email/UPI/ID are already masked in the stored text. Backend is admin-only and gated by
 * CALL_TRANSCRIPT_ENABLED (403 { disabled: true } when off), which is a config state, not an error.
 */
export default function CallTranscriptModal({ open, onClose, sessionId }) {
  const { data, error, isFetching } = useGetCallTranscriptQuery(sessionId, { skip: !open || !sessionId });
  const disabled = error?.status === 403 && error?.data?.disabled;
  const missing = error?.status === 404;

  return (
    <Modal
      open={open}
      onClose={onClose}
      size="xl"
      title="Call transcript"
      description="Auto-generated by speech-to-text. May contain mistakes. Personal details are masked."
    >
      <ModalBody>
        {isFetching && <div className="tw-flex tw-justify-center tw-py-8"><Spinner /></div>}
        {disabled && (
          <ErrorBanner>Call transcript viewing is switched off (CALL_TRANSCRIPT_ENABLED).</ErrorBanner>
        )}
        {missing && (
          <div className="tw-text-sm tw-text-fg-tertiary">
            {error?.data?.message || "No transcript for this call."}
          </div>
        )}
        {error && !disabled && !missing && <ErrorBanner>Failed to load the transcript.</ErrorBanner>}
        {data && (
          <>
            <div className="tw-text-xs tw-text-fg-tertiary tw-mb-2">
              Generated {new Date(data.created_at).toLocaleString()} · kept until{" "}
              {new Date(data.purge_at).toLocaleDateString()}
            </div>
            <div className="tw-whitespace-pre-wrap tw-break-words tw-text-sm tw-leading-relaxed tw-max-h-[60vh] tw-overflow-y-auto">
              {data.transcript || "(empty)"}
            </div>
          </>
        )}
      </ModalBody>
      <ModalFooter>
        <Button variant="ghost" size="sm" onClick={onClose}>Close</Button>
      </ModalFooter>
    </Modal>
  );
}
